#!/usr/bin/env node
/**
 * Generate `lib/client.js` from the hand-written modules under `lib/src/`.
 *
 * The DSH browser module table loads exactly one bundle per package, so the
 * client half must be a single classic script that calls
 * `window.__ModuleLoader__.load({ id, factory })`. To keep the sources small and
 * unit-testable, `lib/src/*.js` are ordinary ESM modules that are concatenated
 * into that one factory body: imports are stripped, top-level `export` keywords
 * are dropped, and every module shares one function scope.
 *
 * Usage:
 *   node scripts/build-client.mjs          # rewrite lib/client.js
 *   node scripts/build-client.mjs --check  # exit 1 when lib/client.js is stale
 */
import { readFile, writeFile } from 'node:fs/promises'
import { dirname, join, relative } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const packageRoot = join(here, '..')
const sourceDir = join(packageRoot, 'lib', 'src')
const outputFile = join(packageRoot, 'lib', 'client.js')

/** Concatenation order: every module may only use identifiers of earlier ones. */
const ORDER = [
  'i18n.js',
  'semver.js',
  'compatibility.js',
  'registry.js',
  'rows.js',
  'ui.js',
  'controller.js',
  'entry.js',
]

const SINGLE_LINE_NAMED_IMPORT =
  /^import\s+\{[^}]*\}\s+from\s+['"][^'"]+['"];?$/

const HEADER = `/**
 * Generated by scripts/build-client.mjs from lib/src/*.js — do not edit by hand.
 * Rebuild with: node scripts/build-client.mjs
 */
`

const PROLOGUE = `window.__ModuleLoader__.load({
  id: '@moyumole/dsh-plugin-updates',
  factory(require) {
    'use strict'
    const React = require('react')
    const h = React.createElement
`

const EPILOGUE = `
    return { inject, apply }
  },
})
`

/**
 * Strip the module syntax one source module contributes to the shared scope.
 * @param {string} file - file name below `lib/src/`, used in diagnostics.
 * @param {string} text - module source.
 * @returns {string} the module body, ready to concatenate.
 */
function transformModule(file, text) {
  const lines = text.split(/\r?\n/)
  const out = []
  for (const [index, line] of lines.entries()) {
    const trimmed = line.trim()
    if (trimmed.startsWith('import ')) {
      if (!SINGLE_LINE_NAMED_IMPORT.test(trimmed)) {
        throw new Error(
          `${file}:${index + 1}: only single-line named imports are supported by the client bundle, ` +
            `found ${JSON.stringify(line)}`,
        )
      }
      continue
    }
    if (trimmed.startsWith('export default')) {
      throw new Error(`${file}:${index + 1}: export default is not supported by the client bundle`)
    }
    if (/^export\s*\{/.test(trimmed)) {
      throw new Error(`${file}:${index + 1}: export { ... } lists are not supported by the client bundle`)
    }
    if (/^export\s+/.test(trimmed)) {
      out.push(line.replace(/^(\s*)export\s+/, '$1'))
      continue
    }
    out.push(line)
  }
  return out.join('\n')
}

/**
 * Build the complete `lib/client.js` text.
 * @returns {Promise<string>} generated bundle source.
 */
async function buildSource() {
  const parts = []
  for (const file of ORDER) {
    const path = join(sourceDir, file)
    let text
    try {
      text = await readFile(path, 'utf8')
    } catch (error) {
      throw new Error(`missing client source ${relative(packageRoot, path)}: ${error.message}`)
    }
    const body = transformModule(file, text).replace(/^\s*\n/, '').replace(/\s+$/, '')
    parts.push(`/* ---- lib/src/${file} ---- */\n${body}`)
  }
  const source = `${HEADER}${PROLOGUE}${parts.join('\n\n')}${EPILOGUE}`
  if (!source.includes('return { inject, apply }')) {
    throw new Error('generated bundle lost its plugin exports')
  }
  return source
}

const check = process.argv.includes('--check')
const generated = await buildSource()
if (check) {
  let current = ''
  try {
    current = await readFile(outputFile, 'utf8')
  } catch {
    current = ''
  }
  if (current !== generated) {
    console.error('lib/client.js is stale; run `node scripts/build-client.mjs` and commit the result')
    process.exit(1)
  }
  console.log('lib/client.js is up to date')
} else {
  await writeFile(outputFile, generated, 'utf8')
  console.log(`wrote ${relative(packageRoot, outputFile)} (${generated.length} bytes)`)
}
